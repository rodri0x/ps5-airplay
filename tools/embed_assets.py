#!/usr/bin/env python3
"""Convert small installer assets into a C translation unit."""
import argparse
import pathlib


def c_bytes(data: bytes) -> str:
    return ", ".join(f"0x{value:02x}" for value in data)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True)
    parser.add_argument("--asset", action="append", required=True)
    args = parser.parse_args()
    out = ["/* generated by tools/embed_assets.py; do not edit */", "#include <stddef.h>", "#include <stdint.h>", ""]
    for spec in args.asset:
        name, path = spec.split("=", 1)
        data = pathlib.Path(path).read_bytes()
        out.append(f"const uint8_t {name}_data[] = {{{c_bytes(data)}}};")
        out.append(f"const size_t {name}_size = sizeof({name}_data);")
        out.append("")
    pathlib.Path(args.output).write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
